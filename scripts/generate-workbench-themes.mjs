import fs from 'node:fs'
import { themes } from '../constant/themes.ts'

// Source data is pinned and checked in; generation never depends on the network.
const { revision, palettes } = JSON.parse(
  fs.readFileSync('data/themes/vscode-upstream.json', 'utf8')
)
const baseCss = fs.readFileSync('css/tailwind.css', 'utf8')
const readBlock = (selector) =>
  Object.fromEntries(
    [
      ...baseCss
        .split(selector)[1]
        .split('}')[0]
        .matchAll(/--vscode-([\w-]+):\s*(#[\da-f]+);/gi),
    ].map((match) => [match[1], match[2]])
  )
const dark = readBlock(':root {')
const light = { ...dark, ...readBlock(':root[data-theme="vscode-light-plus"] {') }
const map = {
  foreground: 'foreground',
  descriptionForeground: 'description-foreground',
  'editor.background': 'editor-background',
  'editor.foreground': 'editor-foreground',
  'editorGroup.border': 'editor-group-border',
  'editorGroupHeader.tabsBackground': 'editor-group-header-tabs-background',
  'editorWidget.background': 'editor-widget-background',
  'widget.border': 'editor-widget-border',
  'titleBar.activeBackground': 'titlebar-active-background',
  'titleBar.activeForeground': 'titlebar-active-foreground',
  'titleBar.inactiveForeground': 'titlebar-inactive-foreground',
  'activityBar.background': 'activitybar-background',
  'activityBar.foreground': 'activitybar-foreground',
  'activityBar.inactiveForeground': 'activitybar-inactive-foreground',
  'activityBar.border': 'activitybar-border',
  'activityBar.activeBorder': 'activitybar-active-border',
  'sideBar.background': 'sidebar-background',
  'sideBar.foreground': 'sidebar-foreground',
  'sideBar.border': 'sidebar-border',
  'sideBarTitle.foreground': 'sidebar-title-foreground',
  'sideBarSectionHeader.background': 'sidebar-section-header-background',
  'sideBarSectionHeader.border': 'sidebar-section-header-border',
  'tab.activeBackground': 'tab-active-background',
  'tab.activeForeground': 'tab-active-foreground',
  'tab.inactiveBackground': 'tab-inactive-background',
  'tab.inactiveForeground': 'tab-inactive-foreground',
  'tab.hoverBackground': 'tab-hover-background',
  'tab.border': 'tab-border',
  'tab.activeBorderTop': 'tab-active-border-top',
  'statusBar.background': 'statusbar-background',
  'statusBar.foreground': 'statusbar-foreground',
  'statusBar.border': 'statusbar-border',
  'statusBarItem.hoverBackground': 'statusbar-item-hover-background',
  'statusBarItem.focusBorder': 'statusbar-item-focus-border',
  'input.background': 'input-background',
  'input.foreground': 'input-foreground',
  'input.border': 'input-border',
  'input.placeholderForeground': 'input-placeholder-foreground',
  'textLink.foreground': 'text-link-foreground',
  'textLink.activeForeground': 'text-link-active-foreground',
  focusBorder: 'focus-border',
  'list.hoverBackground': 'list-hover-background',
  'list.activeSelectionBackground': 'list-active-selection-background',
  'list.activeSelectionForeground': 'list-active-selection-foreground',
  'list.inactiveSelectionBackground': 'list-inactive-selection-background',
  'editor.selectionBackground': 'selection-background',
  'button.background': 'button-background',
  'button.foreground': 'button-foreground',
  'button.hoverBackground': 'button-hover-background',
  'panel.background': 'panel-background',
  'panel.border': 'panel-border',
  'textBlockQuote.background': 'text-blockquote-background',
  'textBlockQuote.border': 'text-blockquote-border',
  'textCodeBlock.background': 'text-code-block-background',
  'icon.foreground': 'icon-foreground',
  'toolbar.hoverBackground': 'toolbar-hover-background',
  'commandCenter.background': 'command-center-background',
  'quickInput.background': 'quick-input-background',
  'breadcrumb.background': 'breadcrumb-background',
  'breadcrumb.foreground': 'breadcrumb-foreground',
  'breadcrumb.focusForeground': 'breadcrumb-focus-foreground',
}
let css = `/* Generated by scripts/generate-workbench-themes.mjs.\n * VS Code ${revision}; Microsoft, MIT (see data/themes/LICENSE).\n * Explicit upstream colors override web fallbacks; source data includes theme inheritance. */\n`
for (const theme of themes.filter((theme) => 'source' in theme)) {
  const tokens = { ...(theme.scheme === 'light' ? light : dark) }
  if (theme.id.includes('hc-'))
    Object.assign(tokens, readBlock(`:root[data-theme="${theme.id}"] {`))
  for (const [upstream, token] of Object.entries(map))
    if (palettes[theme.id].colors[upstream]) tokens[token] = palettes[theme.id].colors[upstream]
  // Upstream omits default registry colors; preserve web equivalents explicitly.
  tokens['sidebar-background'] ||= tokens['editor-widget-background']
  css += `\n:root[data-theme="${theme.id}"] {\n  color-scheme: ${theme.scheme};\n${Object.entries(
    tokens
  )
    .map(([key, value]) => `  --vscode-${key}: ${value};`)
    .join('\n')}\n}\n`
}
fs.writeFileSync('css/themes.css', css)
